-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT plant.ID AS ENTITY_ID, plant.NAME AS ENTITY_NAME,
       plant.REGION, plant.CATEGORY, plant.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(observation.LOSS_EVENT_COUNT) AS LOSS_EVENT_COUNT,
       SUM(observation.OPERATING_HOURS) AS OPERATING_HOURS,
       SUM(observation.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(observation.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(observation.PM_DUE) AS PM_DUE, SUM(observation.PM_COMPLETED) AS PM_COMPLETED,
       SUM(observation.STRING_CHECKS) AS STRING_CHECKS,
       SUM(observation.IN_RANGE_READINGS) AS IN_RANGE_READINGS, SUM(observation.INVERTER_READINGS) AS INVERTER_READINGS,
       SUM(observation.STRING_FAULTS) AS STRING_FAULTS,
       100.0 * SUM(observation.IN_RANGE_READINGS) / NULLIF(SUM(observation.INVERTER_READINGS), 0) AS IN_RANGE_PCT,
       1000.0 * SUM(observation.STRING_FAULTS) / NULLIF(SUM(observation.STRING_CHECKS), 0) AS FAULTS_PER_1K,
       100.0 * SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.PLANNED_HOURS), 0) AS PLANT_AVAILABILITY_PCT,
       100.0 * SUM(observation.PM_COMPLETED) / NULLIF(SUM(observation.PM_DUE), 0) AS PM_COMPLIANCE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.PLANT_DAILY observation
JOIN RAW.PLANTS plant ON plant.ID = observation.ENTITY_ID
GROUP BY plant.ID, plant.NAME, plant.REGION, plant.CATEGORY, plant.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(IN_RANGE_READINGS) AS IN_RANGE_READINGS, SUM(INVERTER_READINGS) AS INVERTER_READINGS,
       SUM(STRING_CHECKS) AS STRING_CHECKS, SUM(STRING_FAULTS) AS STRING_FAULTS,
       SUM(LOSS_EVENT_COUNT) AS LOSS_EVENT_COUNT,
       100.0 * SUM(IN_RANGE_READINGS) / NULLIF(SUM(INVERTER_READINGS), 0) AS IN_RANGE_PCT
FROM RAW.PLANT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.LOSS_EVENT_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(LOSS_EVENT_COUNT) AS LOSS_EVENT_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(INVERTER_READINGS) - SUM(IN_RANGE_READINGS) AS OUT_OF_RANGE_READINGS
FROM RAW.PLANT_DAILY
WHERE LOSS_EVENT_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(IN_RANGE_READINGS) AS IN_RANGE_READINGS, SUM(INVERTER_READINGS) AS INVERTER_READINGS,
         SUM(STRING_CHECKS) AS STRING_CHECKS, SUM(STRING_FAULTS) AS FAILED,
         SUM(LOSS_EVENT_COUNT) AS LOSS_EVENTS,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.PLANT_DAILY
), network AS (SELECT COUNT(*) AS PLANT_COUNT FROM RAW.PLANTS),
readiness AS (
  SELECT 100.0 * SUM(LEAST(ON_HAND_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT
  FROM RAW.EQUIPMENT_READINESS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'In-Range Inverter Readings' AS TITLE,
         100.0 * IN_RANGE_READINGS / NULLIF(INVERTER_READINGS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Generation Loss Events', LOSS_EVENTS, '' FROM observations
  UNION ALL SELECT 3, 'Faults per 1k String Checks', 1000.0 * FAILED / NULLIF(STRING_CHECKS, 0), '' FROM observations
  UNION ALL SELECT 4, 'Inverter Readings', INVERTER_READINGS, '' FROM observations
  UNION ALL SELECT 5, 'Plant Availability', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Solar Plants', PLANT_COUNT, '' FROM network
  UNION ALL SELECT 7, 'Spare Parts Readiness', COVERAGE_PCT, '%' FROM readiness
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.TITLE = 'Faults per 1k String Checks' THEN TRIM(TO_VARCHAR(metrics.VALUE_NUM, '990.00'))
                WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.LOSS_EVENT_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
